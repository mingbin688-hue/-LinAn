/* Run against your own local Linan server. No user browser profile is used. */
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const fs=require('node:fs/promises');
const path=require('node:path');
const root=path.resolve(__dirname,'..');
const url=process.env.LINAN_URL||'http://127.0.0.1:8765';
const pause=ms=>new Promise(r=>setTimeout(r,ms));
(async()=>{
 const browser=await chromium.launch({headless:true,...(process.env.BROWSER_EXECUTABLE?{executablePath:process.env.BROWSER_EXECUTABLE}:{channel:'msedge'})});
 const docs=path.resolve(process.env.LINAN_OUTPUT_DIR||path.join(root,'runtime','browser-check'));await fs.mkdir(docs,{recursive:true});
 const ctx=await browser.newContext({viewport:{width:1440,height:1080},recordVideo:{dir:path.join(docs,'recordings'),size:{width:1440,height:1080}}});
 const page=await ctx.newPage();const errors=[];page.on('pageerror',e=>errors.push(e.message));
 const mark=async text=>{console.log(text);await pause(800)};
 const login=async name=>{
  if(await page.locator('.app-shell').count())await page.getByRole('button',{name:'退出并切换身份'}).click();
  await page.locator('.login-form input').nth(0).fill(name);
  await page.locator('.login-form input').nth(1).fill('Demo2026!');
  await page.getByRole('button',{name:/登录守护工作台/}).click();
  await page.locator('.app-shell').waitFor();
 };
 const nav=label=>page.locator('nav button').filter({hasText:label}).click();
 await page.goto(url);await login('admin');await page.getByRole('heading',{name:'守护总览',exact:true}).waitFor();
 await mark('管理员总览');await page.screenshot({path:path.join(docs,'overview.png'),fullPage:true});
 await nav('老人档案');await page.locator('.resident-card').first().getByRole('button',{name:'查看档案'}).click();
 await page.getByRole('heading',{name:'日常与联系'}).waitFor();await mark('档案与来源');await page.locator('.el-drawer__close-btn:visible').click();
 await nav('回放与实验');await page.getByRole('button',{name:/三位老人，同时需要关注/}).click();await mark('合成情景回放');
 await page.getByRole('button',{name:'回放下一窗口',exact:true}).click();await page.locator('.replay-result').waitFor();await mark('CASAS公开窗口回放');
 await nav('任务中心');
 const recResponse=page.waitForResponse(r=>r.url().endsWith('/api/dispatch/recommend')&&r.request().method()==='POST');
 await page.getByRole('button',{name:'计算派单建议'}).click();const rr=await(await recResponse).json();
 if(!rr.recommendations.length)throw new Error('没有可演示的派单推荐');
 const rec=rr.recommendations[0];await page.locator('.recommendation').first().waitFor();await mark('查看约束与派单理由');
 await page.locator('.recommendation').first().getByRole('button',{name:'确认派单'}).click();
 await page.locator('.el-dialog').filter({hasText:'协同处置 · 派单建议'}).getByRole('button',{name:'关闭',exact:true}).click();
 await mark('管理员确认派单');await login('staff'+rec.staff_id);await page.locator('.task-card').filter({hasText:rec.task_id}).waitFor();
 let card=page.locator('.task-card').filter({hasText:rec.task_id});await card.getByRole('button',{name:'接单',exact:true}).click();
 await card.getByRole('button',{name:'开始处理'}).click();await mark('照护人员接单与处置');
 await card.getByRole('button',{name:'提交处置结果'}).click();
 await page.locator('.el-dialog').filter({hasText:'提交处置结果'}).locator('textarea').fill('演示走访已完成，老人已回应并确认安全。');
 await page.getByRole('button',{name:'确认提交',exact:true}).click();await mark('提交处置反馈');
 await login('admin');await nav('任务中心');card=page.locator('.task-card').filter({hasText:rec.task_id});
 await card.getByRole('button',{name:'核实并关闭'}).click();await page.locator('.el-dialog').filter({hasText:'核实并关闭事件'}).locator('textarea').fill('管理员已复核照护记录，确认安全，关闭事件。');
 await page.getByRole('button',{name:'确认提交',exact:true}).click();await card.getByText('已关闭',{exact:true}).waitFor();
 await card.getByRole('button',{name:'详情与记录'}).click();await page.getByRole('heading',{name:'决策与操作留痕'}).waitFor();
 await mark('闭环与决策审计');await page.screenshot({path:path.join(docs,'decision-trace.png'),fullPage:true});await page.locator('.el-drawer__close-btn:visible').click();
 await nav('回放与实验');await page.getByRole('button',{name:'运行对比实验'}).click();await page.getByRole('heading',{name:'合成数据 · 社区任务调度'}).waitFor();
 await mark('真实计算的实验结果');await page.screenshot({path:path.join(docs,'experiments.png'),fullPage:true});
 await login('family');if(await page.locator('.care-hero').count()!==1)throw new Error('家属范围错误');
 await page.getByRole('button',{name:/我很平安/}).click();await page.getByRole('button',{name:'确认上报',exact:true}).click();await mark('家属回应状态');
 const video=page.video();await ctx.close();await video.saveAs(path.join(docs,'demo.webm'));
 const mobile=await browser.newContext({viewport:{width:390,height:844},isMobile:true,deviceScaleFactor:1});const mp=await mobile.newPage();
 mp.on('pageerror',e=>errors.push(e.message));await mp.goto(url);await mp.getByRole('button',{name:'老人',exact:true}).click();
 await mp.getByRole('heading',{name:'今天过得怎么样？'}).waitFor();
 const overflow=await mp.evaluate(()=>document.documentElement.scrollWidth>innerWidth+1);
 if(overflow)throw new Error('手机页面水平溢出');
 await mp.screenshot({path:path.join(docs,'mobile.png'),fullPage:true});
 await mobile.close();await browser.close();
 const report={success:errors.length===0,js_errors:errors,desktop:'1440x1080',mobile:'390x844',workflow_task:rec.task_id,
   checks:['管理员登录','档案来源','合成情景','CASAS回放','推荐与确认','照护人员接单','处置反馈','管理员复核关闭','决策留痕','实验计算','家属单人权限','老人移动布局']};
 await fs.writeFile(path.join(docs,'browser-check.json'),JSON.stringify(report,null,2));console.log(JSON.stringify(report,null,2));
 if(errors.length)process.exitCode=1;
})().catch(e=>{console.error(e);process.exit(1)});
